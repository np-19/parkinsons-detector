"""Create participant-separated train, validation, and test datasets."""

from __future__ import annotations

import argparse
import shutil
import tempfile
from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split


SEED = 42
SPLITS = ("train", "validation", "test")
REQUIRED_COLUMNS = {"ROW_ID", "healthCode", "label", "filename"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Split mPower recordings by participant without leakage."
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace conflicting files generated by an earlier run.",
    )
    return parser.parse_args()


def load_manifest(root: Path) -> pd.DataFrame:
    manifest_path = root / "data" / "metadata" / "manifest.csv"
    if not manifest_path.is_file():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")

    manifest = pd.read_csv(manifest_path, dtype=str, keep_default_na=False)
    missing = REQUIRED_COLUMNS - set(manifest.columns)
    if missing:
        raise ValueError(f"Manifest is missing columns: {sorted(missing)}")

    for column in REQUIRED_COLUMNS:
        manifest[column] = manifest[column].astype(str).str.strip()

    if manifest["ROW_ID"].eq("").any():
        raise ValueError("Manifest contains an empty ROW_ID.")
    if manifest["ROW_ID"].duplicated().any():
        raise ValueError("Manifest contains duplicate ROW_ID values.")
    if manifest["healthCode"].eq("").any():
        raise ValueError("Manifest contains an empty healthCode.")
    if manifest["label"].eq("").any():
        raise ValueError("Manifest contains an empty label.")
    if manifest["filename"].eq("").any():
        raise ValueError("Manifest contains an empty filename.")

    labels_per_participant = manifest.groupby("healthCode")["label"].nunique()
    contradictory = labels_per_participant[labels_per_participant > 1]
    if not contradictory.empty:
        raise ValueError(
            "A healthCode has more than one label: "
            + ", ".join(contradictory.index[:5])
        )
    return manifest


def assign_participants(manifest: pd.DataFrame) -> dict[str, str]:
    participants = (
        manifest[["healthCode", "label"]]
        .drop_duplicates()
        .sort_values("healthCode")
        .reset_index(drop=True)
    )
    if participants["label"].value_counts().min() < 4:
        raise ValueError(
            "Each label needs at least four participants for stratified splitting."
        )

    train, temporary = train_test_split(
        participants,
        test_size=0.30,
        random_state=SEED,
        stratify=participants["label"],
    )
    validation, test = train_test_split(
        temporary,
        test_size=0.50,
        random_state=SEED,
        stratify=temporary["label"],
    )

    assignments: dict[str, str] = {}
    for split, frame in (
        ("train", train),
        ("validation", validation),
        ("test", test),
    ):
        assignments.update(dict.fromkeys(frame["healthCode"], split))

    if set(assignments) != set(participants["healthCode"]):
        raise RuntimeError("Some participants were not assigned to a split.")
    if len(assignments) != len(participants):
        raise RuntimeError("A participant was assigned to multiple splits.")
    return assignments


def validate_sources(manifest: pd.DataFrame, root: Path) -> None:
    audio_dir = root / "data" / "mPower_Audio"
    missing = []
    unsafe = []
    for filename in manifest["filename"]:
        relative = Path(filename)
        if relative.name != filename or relative.suffix.lower() != ".m4a":
            unsafe.append(filename)
            continue
        sources = [
            audio_dir / split / relative
            for split in SPLITS
            if (audio_dir / split / relative).is_file()
        ]
        if not any(source.stat().st_size > 0 for source in sources):
            missing.append(str(audio_dir / "<split>" / relative))
    if unsafe:
        raise ValueError(f"Unsafe or non-m4a manifest filenames: {unsafe[:5]}")
    if missing:
        raise FileNotFoundError(
            f"{len(missing)} source audio files are missing or empty; "
            f"first missing file: {missing[0]}"
        )


def write_metadata(frame: pd.DataFrame, path: Path, force: bool) -> None:
    if path.exists() and not force:
        existing = pd.read_csv(path, dtype=str, keep_default_na=False)
        expected = frame.astype(str).reset_index(drop=True)
        if existing.astype(str).reset_index(drop=True).equals(expected):
            print(f"Reusing existing metadata: {path}")
            return
        raise FileExistsError(
            f"{path} already exists with different contents. "
            "Use --force to replace generated split files."
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".csv", dir=path.parent, delete=False
    ) as temporary:
        temporary_path = Path(temporary.name)
    try:
        frame.to_csv(temporary_path, index=False)
        temporary_path.replace(path)
    finally:
        temporary_path.unlink(missing_ok=True)


def copy_audio(
    frame: pd.DataFrame, split: str, root: Path, force: bool
) -> None:
    source_dir = root / "data" / "mPower_Audio"
    destination_dir = root / "data" / split
    destination_dir.mkdir(parents=True, exist_ok=True)

    for _, row in frame.iterrows():
        filename = row["filename"]
        label = row["label"]
        source = source_dir / split / label / filename
        destination = destination_dir / label / filename
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            if not destination.is_file() or destination.stat().st_size != source.stat().st_size:
                if not force:
                    raise FileExistsError(
                        f"{destination} conflicts with the source. Use --force to replace it."
                    )
                shutil.copy2(source, destination)
            else:
                print(f"Reusing existing audio: {destination}")
        else:
            shutil.copy2(source, destination)


def print_summary(split_frames: dict[str, pd.DataFrame]) -> None:
    print("\n==============================")
    print("SPLIT COMPLETE")
    print("==============================")
    for split in SPLITS:
        frame = split_frames[split]
        counts = frame["label"].value_counts()
        print(f"\n{split.upper()}")
        print(f"Participants: {frame['healthCode'].nunique():,}")
        print(f"Recordings: {len(frame):,}")
        print(f"PD: {counts.get('PD', 0):,}")
        print(f"CONTROL: {counts.get('CONTROL', 0):,}")
    print("\nParticipant leakage: NONE")


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    args = parse_args()
    manifest = load_manifest(root)
    validate_sources(manifest, root)

    assignments = assign_participants(manifest)
    split_column = manifest["healthCode"].map(assignments)
    if split_column.isna().any():
        raise RuntimeError("Some recordings have no participant split.")

    split_frames = {
        split: manifest.loc[split_column.eq(split)].copy()
        for split in SPLITS
    }
    if set().union(*(set(frame["healthCode"]) for frame in split_frames.values())) != set(
        manifest["healthCode"]
    ):
        raise RuntimeError("Participant assignment does not cover the manifest.")
    if sum(len(frame) for frame in split_frames.values()) != len(manifest):
        raise RuntimeError("Split recording counts do not match the manifest.")

    for split, frame in split_frames.items():
        frame["split"] = split
        copy_audio(frame, split, root, args.force)
        write_metadata(frame, root / "data" / "metadata" / f"{split}.csv", args.force)

    print_summary(split_frames)


if __name__ == "__main__":
    main()
